def preflight(kg, classes):
    """落图前报告：提案名会撞上哪类既有节点（避免静默意外）。"""
    canon = gx.build_canon_index(kg)
    seen = set()
    new, blocked = [], []
    for _bid, items in GROUPS:
        for it in items:
            for nm in it["nodes"]:
                if nm in seen:
                    continue
                seen.add(nm)
                hit = gx.canonicalize(nm, canon, kg)
                if hit:
                    blocked.append((nm, hit, classes.get(hit, "?")))
                else:
                    new.append(nm)
    return new, blocked


def main():
    os.makedirs(WORK_DIR, exist_ok=True)
    kg = KnowledgeGraph.load(GRAPH_PATH)
    degree = gx.node_degree(kg)
    classes = gx.classify_all(kg)
    before = gx.graph_stats(kg, classes, degree)

    proposed, blocked = preflight(kg, classes)
    logger.info(f"[Preflight] 新建提案 {len(proposed)}；命中既有 {len(blocked)}")
    for nm, hit, cl in blocked:
        logger.info(f"  {nm} → {hit} ({cl})")

    state = gx.load_state(STATE_PATH)
    state["_classes"] = classes
    guard = {"min_confidence": 0.6, "max_edges_per_seed": 20,
             "max_new_nodes_per_seed": 8, "new_node_budget": 500,
             "new_edge_budget": 1500}
    canon_index = gx.build_canon_index(kg)
    totals = {"new_nodes": 0, "new_edges": 0, "merged": 0, "rejected": {}}
    for bid, items in GROUPS:
        lines = []
        st = gx.apply_items(kg, items, canon_index, state, bid, guard, lines)
        with open(LEDGER_PATH, "a", encoding="utf-8") as f:
            for ln in lines:
                f.write(ln + "\n")
        gx.save_state(STATE_PATH, state)
        kg.save(GRAPH_PATH)          # 每组落盘一次（断点安全）
        totals["new_nodes"] += st["new_nodes"]
        totals["new_edges"] += st["new_edges"]
        totals["merged"] += st["merged_edges"]
        for k, v in st["rejected"].items():
            totals["rejected"][k] = totals["rejected"].get(k, 0) + v
        logger.info(f"[{bid}] +节点{st['new_nodes']} +边{st['new_edges']} "
                    f"合并{st['merged_edges']} 拒{sum(st['rejected'].values())}")

    # —— 别名收口（复用既有 aliases 机制，不删节点）——
    ALIAS_ADDS = {
        "日本麻将": ["立直麻将", "日麻"],
        "人工智能": ["AI"],
        "大语言模型": ["LLM", "大型语言模型"],
        "昼夜节律": ["生物钟"],
        "编程": ["程序设计"],
        "役种": ["役"],
    }
    for nid, als in ALIAS_ADDS.items():
        n = kg.nodes.get(nid)
        if n is None:
            continue
        cur = list((n.extra_attrs or {}).get("aliases") or [])
        add = [a for a in als if a not in cur
               and gx._norm_name(a) not in canon_index]
        if add:
            cur += add
            n.extra_attrs = {**(n.extra_attrs or {}), "aliases": cur}
            for a in add:
                canon_index.setdefault(gx._norm_name(a), nid)
    kg.save(GRAPH_PATH)

    degree = gx.node_degree(kg)
    classes = gx.classify_all(kg)
    after = gx.graph_stats(kg, classes, degree)
    rep = {"before": before, "after": after, "totals": totals,
           "new_node_names": sorted(set(proposed)) and proposed,
           "blocked": blocked,
           "top_degree_after": gx.top_nodes(kg, degree, 20)}
    rpt = os.path.join(
        WORK_DIR, f"claude_report_{time.strftime('%Y%m%d_%H%M%S')}.json")
    with open(rpt, "w", encoding="utf-8") as f:
        json.dump(rep, f, ensure_ascii=False, indent=1)
    print(json.dumps({k: rep[k] for k in ("before", "after", "totals")},
                     ensure_ascii=False, indent=1))
    logger.info(f"[Done] 报告 → {rpt}")


if __name__ == "__main__":
    main()
